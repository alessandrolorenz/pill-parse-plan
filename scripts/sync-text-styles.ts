/**
 * sync-text-styles.ts
 * Fetches text styles from the Figma REST API and generates
 * src/lib/text-styles.ts with typed TypeScript constants.
 *
 * Usage:
 *   FIGMA_TOKEN=<pat> npx tsx --tsconfig tsconfig.scripts.json scripts/sync-text-styles.ts
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { FIGMA_FILE_KEY, FIGMA_TOKEN, FIGMA_API_BASE } from './figma-config.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT_FILE = path.resolve(__dirname, '../src/lib/text-styles.ts');

// ─── Types ────────────────────────────────────────────────────────────────────

interface FigmaStyle {
  key: string;
  name: string;
  style_type: string;
  description: string;
}

interface FigmaStylesResponse {
  meta: { styles: FigmaStyle[] };
}

interface FigmaNodeStyle {
  fontFamily: string;
  fontWeight: number;
  fontSize: number;
  lineHeightPx: number;
  letterSpacing: number;
  textCase: string;
  textDecoration: string;
}

interface FigmaNodesResponse {
  nodes: Record<string, { document: { style: FigmaNodeStyle } }>;
}

// ─── Helpers ──────────────────────────────────────────────────────────────────

/** Convert a Figma style name like "heading/h1" → "headingH1" (camelCase) */
function toCamelCase(name: string): string {
  return name
    .replace(/[^a-zA-Z0-9/]/g, ' ')
    .split(/[/ ]+/)
    .map((part, i) => i === 0 ? part.toLowerCase() : part.charAt(0).toUpperCase() + part.slice(1).toLowerCase())
    .join('');
}

/** Convert font weight number to CSS keyword */
function fontWeightLabel(w: number): string {
  const map: Record<number, string> = {
    100: 'thin', 200: 'extralight', 300: 'light', 400: 'normal',
    500: 'medium', 600: 'semibold', 700: 'bold', 800: 'extrabold', 900: 'black',
  };
  return map[w] ?? String(w);
}

async function fetchStyles(): Promise<FigmaStyle[]> {
  const url = `${FIGMA_API_BASE}/files/${FIGMA_FILE_KEY}/styles`;
  const res = await fetch(url, { headers: { 'X-Figma-Token': FIGMA_TOKEN } });
  if (!res.ok) throw new Error(`Figma API error ${res.status}: ${await res.text()}`);
  const data = await res.json() as FigmaStylesResponse;
  return data.meta.styles.filter(s => s.style_type === 'TEXT');
}

async function fetchNodeStyles(nodeIds: string[]): Promise<FigmaNodesResponse> {
  const ids = nodeIds.join(',');
  const url = `${FIGMA_API_BASE}/files/${FIGMA_FILE_KEY}/nodes?ids=${encodeURIComponent(ids)}&depth=1`;
  const res = await fetch(url, { headers: { 'X-Figma-Token': FIGMA_TOKEN } });
  if (!res.ok) throw new Error(`Figma API error ${res.status}: ${await res.text()}`);
  return res.json() as Promise<FigmaNodesResponse>;
}

// ─── Main ─────────────────────────────────────────────────────────────────────

async function main() {
  if (!FIGMA_TOKEN) {
    console.error('❌  FIGMA_TOKEN environment variable is not set.');
    process.exit(1);
  }

  console.log('🔍  Fetching Figma text styles…');
  const styles = await fetchStyles();

  if (styles.length === 0) {
    console.warn('⚠️  No text styles found in the Figma file.');
    return;
  }

  console.log(`   Found ${styles.length} text style(s).`);

  // Fetch node details for each style to get typography values
  // Figma style keys are used as node IDs in the /nodes endpoint
  const styleKeys = styles.map(s => s.key);
  let nodeData: FigmaNodesResponse | null = null;

  try {
    nodeData = await fetchNodeStyles(styleKeys);
  } catch (err) {
    console.warn('⚠️  Could not fetch node details — generating stubs only.', err);
  }

  // Build TypeScript output
  const lines: string[] = [
    '/**',
    ' * text-styles.ts — AUTO-GENERATED by scripts/sync-text-styles.ts',
    ' * DO NOT EDIT MANUALLY. Run `npm run script:sync-text-styles` to regenerate.',
    ' *',
    ` * Source: Figma file ${FIGMA_FILE_KEY}`,
    ` * Generated: ${new Date().toISOString()}`,
    ' */',
    '',
    'export interface TextStyle {',
    '  fontFamily: string;',
    '  fontSize: number;',
    '  fontWeight: number;',
    '  lineHeight: number;',
    '  letterSpacing: number;',
    '  /** Tailwind class string for this text style */',
    '  tailwind: string;',
    '}',
    '',
    'export const textStyles = {',
  ];

  for (const style of styles) {
    const key = toCamelCase(style.name);
    const nodeId = style.key;
    const nodeDoc = nodeData?.nodes?.[nodeId]?.document;
    const s = nodeDoc?.style;

    if (s) {
      const lh = s.lineHeightPx ? Math.round((s.lineHeightPx / s.fontSize) * 100) / 100 : 1.5;
      const ls = s.letterSpacing ? `${(s.letterSpacing / s.fontSize).toFixed(3)}em` : '0em';
      const twSize = fontSizeToTailwind(s.fontSize);
      const twWeight = `font-${fontWeightLabel(s.fontWeight)}`;

      lines.push(`  /** ${style.name}${style.description ? ` — ${style.description}` : ''} */`);
      lines.push(`  ${key}: {`);
      lines.push(`    fontFamily: '${s.fontFamily}',`);
      lines.push(`    fontSize: ${s.fontSize},`);
      lines.push(`    fontWeight: ${s.fontWeight},`);
      lines.push(`    lineHeight: ${lh},`);
      lines.push(`    letterSpacing: ${s.letterSpacing ?? 0},`);
      lines.push(`    tailwind: '${twSize} ${twWeight} leading-[${lh}] tracking-[${ls}]',`);
      lines.push(`  },`);
    } else {
      // Stub when node data is unavailable
      lines.push(`  /** ${style.name} */`);
      lines.push(`  ${key}: { fontFamily: 'Inter', fontSize: 16, fontWeight: 400, lineHeight: 1.5, letterSpacing: 0, tailwind: 'text-base font-normal' },`);
    }
  }

  lines.push('} satisfies Record<string, TextStyle>;');
  lines.push('');
  lines.push('export type TextStyleKey = keyof typeof textStyles;');
  lines.push('');

  // Ensure output directory exists
  const outDir = path.dirname(OUT_FILE);
  if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });

  fs.writeFileSync(OUT_FILE, lines.join('\n'), 'utf-8');
  console.log(`✅  Generated ${styles.length} text style(s) → src/lib/text-styles.ts`);
}

/** Map px font size to nearest Tailwind text-* class */
function fontSizeToTailwind(px: number): string {
  if (px <= 12) return 'text-xs';
  if (px <= 14) return 'text-sm';
  if (px <= 16) return 'text-base';
  if (px <= 18) return 'text-lg';
  if (px <= 20) return 'text-xl';
  if (px <= 24) return 'text-2xl';
  if (px <= 30) return 'text-3xl';
  if (px <= 36) return 'text-4xl';
  if (px <= 48) return 'text-5xl';
  return 'text-6xl';
}

main().catch(err => {
  console.error('❌  sync-text-styles failed:', err);
  process.exit(1);
});